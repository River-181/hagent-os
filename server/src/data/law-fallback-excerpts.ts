/**
 * 쿼리가 fallback 엔트리의 keywords 중 하나라도 부분 문자열로 포함하면 매칭.
 * 대소문자·공백 무시. 첫 번째 매칭만 반환.
 */
export function findLawFallback(query: string): LawFallbackEntry | null {
  if (!query) return null
  const normalized = query.toLowerCase().replace(/\s+/g, "")
  for (const entry of LAW_FALLBACK_EXCERPTS) {
    if (entry.keywords.some((kw) => normalized.includes(kw.toLowerCase()))) {
      return entry
    }
  }
  return null
}
